// Rebuild a package's `src/notation.generated.ts` from each head's `reference/<Head>/notation.json`,
// so its `./notation` entry carries the data without reading the records at run time. Run by the
// package's `build`:
//
//   node <manifest>/scripts/collect-notation.ts <package-dir>

import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { headNames, readHead, writeFormatted } from "@enumeratio/entry/node";
import { type NotationData, notationProblem } from "../src/notation-data.ts";

const root = resolve(process.argv[2] ?? ".");
const dir = `${root}/reference/`;

const notation: Record<string, NotationData> = {};
for (const head of headNames(dir)) {
  const data = readHead(dir, head).notation as NotationData | undefined;
  if (data === undefined) continue;
  const problem = notationProblem(data);
  if (problem !== undefined) throw new Error(`${head}'s notation.json: ${problem}`);
  notation[head] = data;
}

await writeFormatted(
  new URL("src/notation.generated.ts", pathToFileURL(`${root}/`)),
  `// GENERATED by @enumeratio/manifest's scripts/collect-notation.ts from reference/<Head>/notation.json; never committed.

import type { NotationData } from "@enumeratio/manifest";

export const NOTATION_DATA: Readonly<Record<string, NotationData>> = ${JSON.stringify(notation)};
`,
);
