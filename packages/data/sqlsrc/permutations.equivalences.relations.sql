INSERT INTO base_example (suite, title, kind, expected, description, sql) VALUES

  -- CONJUGACY -----------------------------------------------------------------------------------------------
  ('element_relations', 'conjugacy class of 312 (a 3-cycle) = {231, 312}: the two 3-cycles on {1,2,3}',
   'eq', '231,312', 'the orbit as a set of carrier values',$q$
    SELECT string_agg(one_line(c), ',' ORDER BY one_line(c)) FROM perm_conjugacy_class(ROW(ARRAY[3,1,2])::permutation) c $q$),
  ('element_relations', 'conjugacy class of 2143 (cycle type 2+2) = {2143, 3412, 4321}: the three double-transpositions of S_4',
   'eq', '2143,3412,4321', 'a second concrete class, at a different cycle type',$q$
    SELECT string_agg(one_line(c), ',' ORDER BY one_line(c)) FROM perm_conjugacy_class(ROW(ARRAY[2,1,4,3])::permutation) c $q$),
  ('element_relations', 'the conjugacy orbit is a well-defined class: every member shares one canonical representative, permutations(4)',
   'eq', 'true', 'orbit:conjugacy is the kernel of the representative map',$q$
    SELECT bool_and(perm_conjugacy_class_representative(c) = perm_conjugacy_class_representative((e).value))::text
      FROM elements(permutations(4)) e, LATERAL perm_conjugacy_class((e).value) c $q$),
  ('element_relations', 'the canonical representative is conjugacy-invariant: it always has the SAME cycle type as its class, n=0..5',
   'eq', 'true', 'canonical_fn never leaves the class it represents',$q$
    SELECT bool_and(perm_cycle_type(perm_conjugacy_class_representative((e).value)) = perm_cycle_type((e).value))::text
      FROM generate_series(0,5) n, LATERAL elements(permutations(n)) e $q$),
  ('element_relations', '#conjugacy classes of S_n = p(n), the partition count (one class per cycle type), n=0..5',
   'eq', 'true', 'GROUP BY orbit:conjugacy = GROUP BY map:conjugacy_class_representative — brute-verified against cardinality(integer_partitions(n))',$q$
    SELECT bool_and(
      (SELECT count(DISTINCT perm_conjugacy_class_representative((e).value)) FROM elements(permutations(n)) e)
      = cardinality(integer_partitions(n))
    )::text FROM generate_series(0,5) n $q$),

  -- KNUTH (PLACTIC) EQUIVALENCE -------------------------------------------------------------------------------
  ('element_relations', 'Knuth class of 213 = {213, 231}: both RSK-insert to the same P tableau',
   'eq', '213,231', 'the orbit as a set of carrier values',$q$
    SELECT string_agg(one_line(c), ',' ORDER BY one_line(c)) FROM perm_knuth_class(ROW(ARRAY[2,1,3])::permutation) c $q$),
  ('element_relations', 'Knuth class of 132 = {132, 312}: the OTHER shape-2+1 class at n=3 (disjoint from 213''s class)',
   'eq', '132,312', 'a second concrete class of the same shape, distinct P tableau',$q$
    SELECT string_agg(one_line(c), ',' ORDER BY one_line(c)) FROM perm_knuth_class(ROW(ARRAY[1,3,2])::permutation) c $q$),
  ('element_relations', 'the Knuth orbit is a well-defined class: every member shares one canonical representative, permutations(4)',
   'eq', 'true', 'orbit:knuth is the kernel of the representative map',$q$
    SELECT bool_and(perm_knuth_class_representative(c) = perm_knuth_class_representative((e).value))::text
      FROM elements(permutations(4)) e, LATERAL perm_knuth_class((e).value) c $q$),
  ('element_relations', 'the canonical representative shares the SAME RSK insertion tableau P as its class, n=0..5',
   'eq', 'true', 'canonical_fn never leaves the class it represents — the defining property, since P alone identifies a Knuth class',$q$
    SELECT bool_and(perm_rsk_insertion(perm_knuth_class_representative((e).value)) = perm_rsk_insertion((e).value))::text
      FROM generate_series(0,5) n, LATERAL elements(permutations(n)) e $q$),
  ('element_relations', '#Knuth classes of S_n = #P-tableaux of size n = Σ f^λ over λ⊢n = the involution count (telephone numbers), n=0..5',
   'eq', 'true', 'RSK is a bijection permutations(n) ↔ (P,Q) pairs; distinct P values = distinct classes = |standard_tableaux(n)| = |involutions(n)| (self-inverse under RSK)',$q$
    SELECT bool_and(
      (SELECT count(DISTINCT perm_knuth_class_representative((e).value)) FROM elements(permutations(n)) e)
      = cardinality(standard_tableaux(n))
      AND cardinality(standard_tableaux(n)) = cardinality(involutions(n))
    )::text FROM generate_series(0,5) n $q$);
