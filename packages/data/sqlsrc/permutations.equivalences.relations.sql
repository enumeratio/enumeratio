-- requires: maps, standard_tableaux.stats, element_relations, orbit_maps_permutations_subsets, restrictions
-- permutations — element-relations batch 5 of #237 (the final "Equivalences" group): conjugacy (same cycle type)
-- and Knuth/plactic equivalence (same RSK insertion tableau). Both kind='equivalence', mirroring the words/rotation
-- prototype (element_relations.sql): forward_fn returns the FULL orbit (not a cheap successor step — an
-- equivalence class, unlike a cover, has no natural "next"), and canonical_fn names an idempotent representative
-- map, per crux (b) of docs/design/element-relations.md. Reuses existing machinery rather than re-deriving it:
--   conjugacy_canonical  = perm_conjugacy_class_representative (orbit_maps_permutations_subsets.sql) — already
--                           built directly from perm_cycle_type (maps.sql), already proven idempotent + class-
--                           preserving there. This file adds only the missing half: the orbit itself.
--   knuth_canonical       = built here from perm_rsk_insertion / rsk_inverse (maps.sql) — no prior map existed.
-- Both class-count identities (#classes(n) = p(n) for conjugacy; #classes(n) = telephone numbers for Knuth) were
-- brute-verified against cardinality(integer_partitions(n)) / cardinality(standard_tableaux(n)) /
-- cardinality(involutions(n)) for n=0..6 in a throwaway pglite script before being encoded as examples below.

-- ── equivalence: permutations, conjugacy (same cycle type) ──────────────────────────────────────────────────
-- x ~ y iff they have the same cycle type (the standard S_n conjugacy classes: y = σxσ⁻¹ for some σ iff cycle
-- type matches). forward_fn is the FULL class, not a cheap successor — brute-filtered against the same-size
-- fiber, which is fine at the example sizes here (n ≤ 5, |S_5| = 120). canonical_fn reuses the existing
-- perm_conjugacy_class_representative (orbit_maps_permutations_subsets.sql): the permutation built directly from
-- cycle_type's non-increasing part list, laying each cycle out as consecutive increasing integers.
CREATE FUNCTION perm_conjugacy_class(p permutation) RETURNS SETOF permutation LANGUAGE sql IMMUTABLE AS $$
  SELECT (e).value FROM elements(permutations(coalesce(array_length((p).image,1),0))) e
   WHERE perm_cycle_type((e).value) = perm_cycle_type(p) $$;

-- ── equivalence: permutations, Knuth (plactic) equivalence ───────────────────────────────────────────────────
-- x ~ y iff RSK insertion gives the same P tableau (perm_rsk_insertion(x) = perm_rsk_insertion(y)) — the classic
-- plactic-monoid classes, generated by the elementary Knuth relations on adjacent triples. forward_fn is again the
-- full class, brute-filtered by matching P over the same-size fiber.
CREATE FUNCTION perm_knuth_class(p permutation) RETURNS SETOF permutation LANGUAGE sql IMMUTABLE AS $$
  SELECT (e).value FROM elements(permutations(coalesce(array_length((p).image,1),0))) e
   WHERE perm_rsk_insertion((e).value) = perm_rsk_insertion(p) $$;

-- canonical_fn for Knuth equivalence: the permutation recovered by inverse-RSK from p's OWN insertion tableau P,
-- paired with the canonical "row-major" recording tableau of the same shape (cells 1..λ1 fill row 0, the next λ2
-- fill row 1, etc — always standard, since each row's whole value range sits below the next row's). Idempotent and
-- class-preserving by construction: rsk_inverse(P, Q) always has RSK insertion tableau exactly P (the RSK inverse
-- property), so re-applying the map starts from the same P and rebuilds the same Q, hence the same permutation.
-- (Both properties, plus well-definedness — same class in ⟺ same canonical out, checked over all of S_4×S_4 — were
-- verified in the same throwaway script mentioned above.)
CREATE FUNCTION perm_knuth_class_representative(p permutation) RETURNS permutation LANGUAGE plpgsql IMMUTABLE AS $$
  DECLARE n int := coalesce(array_length((p).image,1),0); parts int[]; rw int[]; base int := 0; r int; i int;
  BEGIN
    IF n = 0 THEN RETURN ROW(ARRAY[]::int[])::permutation; END IF;
    parts := (standard_tableau_shape(perm_rsk_insertion(p))).parts;
    rw := array_fill(0, ARRAY[n]);
    FOR r IN 1..array_length(parts,1) LOOP
      FOR i IN base+1 .. base+parts[r] LOOP rw[i] := r-1; END LOOP;
      base := base + parts[r];
    END LOOP;
    RETURN rsk_inverse(perm_rsk_insertion(p), ROW(rw)::standard_tableau);
  END $$;

