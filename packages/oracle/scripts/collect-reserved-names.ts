// Rewrite `src/reserved-names-data.ts` from the Python lanes' own runtimes (`reserved-names.ts`):
// the names a bare identifier we emit there would be captured by. Committed, not built: it needs
// SymPy, mpmath and Sage installed, and tests/reserved-names.test.ts fails when a runtime
// disagrees with it.
//
//   node packages/oracle/scripts/collect-reserved-names.ts

import { writeFormatted } from "@enumeratio/entry/node";
import { LANES, laneNamespace, pythonNamespace } from "./reserved-names.ts";

const python = pythonNamespace();
if (python === undefined) throw new Error("python3 did not answer");
const base = new Set(python.names);

const runtimes: Record<string, string> = { python: python.version };
const lanes: Record<string, readonly string[]> = {};
for (const lane of LANES) {
  const found = laneNamespace(lane);
  if (found === undefined) throw new Error(`${lane}: its runtime did not answer`);
  runtimes[lane] = found.version;
  lanes[lane] = found.names.filter((name) => !base.has(name));
}

/** Names as lines of words, so a library release reads as a few changed lines. */
function words(names: readonly string[]): string {
  const lines: string[] = [];
  let line = "";
  for (const name of names) {
    if (line !== "" && line.length + 1 + name.length > 96) {
      lines.push(line);
      line = name;
    } else line = line === "" ? name : `${line} ${name}`;
  }
  return `\`\n${[...lines, line].join("\n")}\n\``;
}

await writeFormatted(
  new URL("../src/reserved-names-data.ts", import.meta.url),
  `// GENERATED by packages/oracle/scripts/collect-reserved-names.ts — do not edit by hand.
//
// The names a Python lane's evaluation namespace already holds: Python's keywords and builtins
// (\`python\`), and what each lane's prelude adds to them (\`from sympy import *\`, Sage's own
// namespace). Regenerate with:
//
//   node packages/oracle/scripts/collect-reserved-names.ts

/** The releases the sets below came from. */
const runtimes = ${JSON.stringify(runtimes, null, 2)};

export const RESERVED_NAMES_DATA = {
  runtimes,
  python: ${words(python.names)},
${LANES.map((lane) => `  ${lane}: ${words(lanes[lane]!)},`).join("\n")}
} as const;
`,
);

process.stdout.write(
  `reserved names: python ${python.names.length}, ${LANES.map((lane) => `${lane} +${lanes[lane]!.length}`).join(", ")}\n`,
);
