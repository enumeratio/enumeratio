// Write `src/patches/registry-data.ts`: every `src/patches/<slug>.ts` that exports a `Patch`,
// as the `PATCHES` array. Adding or retiring a patch is then one file, with no registry line
// to conflict on.
//
//   vp node packages/ce-patches/scripts/generate-patches.ts

import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/patches/", import.meta.url);

/** The patch files and the `Patch` each exports, in file-name order. */
export function patchExports(): { file: string; name: string }[] {
  const found: { file: string; name: string }[] = [];
  for (const file of readdirSync(dir).toSorted()) {
    if (!file.endsWith(".ts") || file === "registry-data.ts") continue;
    const match = /^export const (\w+): Patch\b/m.exec(readFileSync(new URL(file, dir), "utf8"));
    if (match?.[1] !== undefined) found.push({ file, name: match[1] });
  }
  return found;
}

export function renderRegistry(patches: readonly { file: string; name: string }[]): string {
  const names = patches.map((p) => p.name);
  if (new Set(names).size !== names.length) throw new Error(`two patches export the same name: ${names.join(", ")}`);
  return `// GENERATED by scripts/generate-patches.ts — do not edit by hand.

import type { Patch } from "../patch.ts";
${patches.map((p) => `import { ${p.name} } from "./${p.file}";`).join("\n")}

/** Every patch offered upstream. \`tests/landed.test.ts\` holds each one to being unfixed. */
export const PATCHES: readonly Patch[] = [${names.map((n) => `\n  ${n},`).join("")}
];
`;
}

export function generatePatches(): number {
  const patches = patchExports();
  writeFileSync(new URL("registry-data.ts", dir), renderRegistry(patches));
  return patches.length;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(`${generatePatches()} patches registered`);
}
