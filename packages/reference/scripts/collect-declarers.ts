// Which of our libraries declares each name, found by declaring them: each library into a fresh
// engine that already holds what it requires, and the names it adds or redefines are its own.
// The manifest reads records and loads no code, so a head whose record doesn't say which
// package declares it (a collection family filed under reference/entries) is only known here.
// The resolver (`@enumeratio/manifest`'s `packagesFor`) reads the result.
//
//   vp node packages/reference/scripts/collect-declarers.ts

import { writeFormatted } from "@enumeratio/entry/node";
import { plan } from "@enumeratio/manifest";
import { canonicalNames, declarers } from "./declarers.ts";
import { LIBRARIES } from "./engines.ts";

const OUT = new URL("../../manifest/src/declarers-data.ts", import.meta.url);

const table = declarers(LIBRARIES, plan);
const canonical = canonicalNames(LIBRARIES);
const text = `// GENERATED by packages/reference/scripts/collect-declarers.ts -- do not edit by hand.
//
// Which of our libraries declares (or redeclares) each name, found by declaring each into a
// fresh engine over what it requires. Regenerate after a library adds or drops a head:
//
//   vp node packages/reference/scripts/collect-declarers.ts

export const DECLARERS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(table, null, 2)};

// The heads each head canonicalises to (\`Lb(x)\` is \`Log(x, 2)\`), which an expression needs too.
export const CANONICAL: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(canonical, null, 2)};
`;
await writeFormatted(OUT, text);
console.log(
  `${Object.keys(table).length} names declared by ${LIBRARIES.length} libraries; ${Object.keys(canonical).length} canonicalise to others`,
);
