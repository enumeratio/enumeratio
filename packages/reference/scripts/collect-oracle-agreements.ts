// Rebuild `src/crosswalk/oracle-agreements-data.ts`: per head, how each crosswalk system's kernel
// fared on its examples (the crosswalk chips' score), tallied from the records' sidecars. The
// crosswalk runs in the browser and cannot load the examples to count them, so it reads this.
//
//   vp node packages/reference/scripts/collect-oracle-agreements.ts

import { writeFormatted } from "@enumeratio/entry/node";
import { oracleAgreementsOf, referenceData } from "../src/node.ts";

const agreements = oracleAgreementsOf(referenceData());

await writeFormatted(
  new URL("../src/crosswalk/oracle-agreements-data.ts", import.meta.url),
  `// GENERATED by scripts/collect-oracle-agreements.ts — do not edit by hand.
//
// Per head, each system's agree/disagree tally over its examples, from the records' oracle
// sidecars. Regenerate with:
//
//   vp node packages/reference/scripts/collect-oracle-agreements.ts

import type { OracleAgreement } from "./oracle.ts";

export const ORACLE_AGREEMENTS: Readonly<Record<string, readonly OracleAgreement[]>> = ${JSON.stringify(agreements, null, 2)};
`,
);

console.log(`${Object.keys(agreements).length} heads with oracle agreements`);
