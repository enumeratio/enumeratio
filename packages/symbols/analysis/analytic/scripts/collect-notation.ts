// Rebuild `src/notation.generated.ts` from each head's `reference/<Head>/notation.json`, so the
// `./notation` entry carries the data without reading the records at run time. Run by `build`.
//
//   node packages/symbols/analysis/analytic/scripts/collect-notation.ts

import { headNames, readHead, writeFormatted } from "@enumeratio/entry/node";
import { type NotationData, notationProblem } from "@enumeratio/manifest";

const dir = new URL("../reference/", import.meta.url).pathname;

const notation: Record<string, NotationData> = {};
for (const head of headNames(dir)) {
  const data = readHead(dir, head).notation as NotationData | undefined;
  if (data === undefined) continue;
  const problem = notationProblem(data);
  if (problem !== undefined) throw new Error(`${head}'s notation.json: ${problem}`);
  notation[head] = data;
}

await writeFormatted(
  new URL("../src/notation.generated.ts", import.meta.url),
  `// GENERATED by scripts/collect-notation.ts from reference/<Head>/notation.json; never committed.

import type { NotationData } from "@enumeratio/manifest";

export const NOTATION_DATA: Readonly<Record<string, NotationData>> = ${JSON.stringify(notation)};
`,
);
