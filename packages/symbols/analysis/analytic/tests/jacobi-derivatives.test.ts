for (const [head, byOrder] of Object.entries(PARTIALS)) {
  test(`${head}: ∂ᵤ up to order 4, ∂ₘ up to order 2 and ∂ᵤ∂ₘ`, () => {
    for (const [orders, values] of Object.entries(byOrder)) {
      const [a, b] = orders.split(",").map(Number);
      values.forEach((wolfram, i) => {
        const [u, m] = POINTS[i]!;
        const ours = ce.box(["N", ["Apply", ["Derivative", head, a, b], u, m]] as never).N().re;
        expect(close(ours, wolfram), `${head} (${orders}) point ${i}: ${ours} vs ${wolfram}`).toBe(true);
      });
    }
  });
}

test("D in u and in m gives the closed forms", () => {
  const [u, m] = [0.37, 0.41];
  const at = (head: string, wrt: string): number =>
    ce
      .box(["D", [head, "u", "m"], wrt] as never)
      .evaluate()
      .subs({ u, m })
      .N().re;
  const f = (name: string, ...args: unknown[]): number => ce.box([name, ...args] as never).N().re;
  const [sn, cn, dn] = [f("JacobiSN", u, m), f("JacobiCN", u, m), f("JacobiDN", u, m)];
  expect(at("JacobiSN", "u")).toBeCloseTo(cn * dn, 12);
  expect(at("JacobiCS", "u")).toBeCloseTo(-dn / (sn * sn), 12);
  // ∂ₘ sn = cn·dn·((1−m)u − ε + m·sn·cn/dn)/(2m(1−m)), with ε = E(am(u, m), m)
  const eps = f("EllipticE", ["JacobiAmplitude", u, m], m);
  const closed = (cn * dn * ((1 - m) * u - eps + (m * sn * cn) / dn)) / (2 * m * (1 - m));
  expect(at("JacobiSN", "m")).toBeCloseTo(closed, 12);
});

test("Series in m at 0: every head's coefficients against Wolfram's SeriesCoefficient", () => {
  for (const [head, wolfram] of Object.entries(M_COEFFICIENTS)) {
    const coefficients = jacobiMCoefficients(head, 4, ["Rational", 9, 10], () => false, [9n, 10n])!;
    coefficients.forEach((json, k) => {
      const ours = ce.box(json as never).N().re;
      expect(close(ours, wolfram[k]!), `${head} m^${k}: ${ours} vs ${wolfram[k]}`).toBe(true);
    });
  }
});

test("Series in m at 0 through Series: the polynomial tracks the function to its order", () => {
  for (const head of Object.keys(M_COEFFICIENTS)) {
    const series = ce.box(["Series", [head, ["Rational", 9, 10], "m"], "m", 0, 3] as never).evaluate();
    expect(series.operator, head).toBe("Add");
    expect(
      operandsOf(series).some((term) => term.operator === "BigO"),
      head,
    ).toBe(true);
    const polynomial = ce.function(
      "Add",
      operandsOf(series).filter((term) => term.operator !== "BigO"),
    );
    const m = 0.02;
    const function_ = ce.box([head, ["Rational", 9, 10], m] as never).N().re;
    // the remainder is O(m⁴): about 1e-7 at m = 0.02
    expect(Math.abs(polynomial.subs({ m }).N().re - function_), head).toBeLessThan(1e-6);
  }
});

test("Series in u at the pole u = 0 and at a symbolic point", () => {
  // Wolfram: Series[JacobiCS[u, 1/3], {u, 0, 3}] = 1/u - 5u/18 - 41u³/3240 + O(u⁴)
  expect(ce.box(["Series", ["JacobiCS", "u", ["Rational", 1, 3]], "u", 0, 3] as never).evaluate().json).toEqual([
    "Add",
    ["Multiply", ["Rational", -41, 3240], ["Power", "u", 3]],
    ["Multiply", ["Rational", -5, 18], "u"],
    ["Divide", 1, "u"],
    ["BigO", ["Power", "u", 4]],
  ]);
  // Wolfram: Series[JacobiSN[u, m], {u, u0, 2}] = sn + cn·dn·(u−u0) − (m·cn² + dn²)·sn·(u−u0)²/2
  const series = ce.box(["Series", ["JacobiSN", "u", "m"], "u", "u0", 2] as never).evaluate();
  const [u0, m, h] = [0.4, 0.3, 0.1];
  const value = ce
    .function(
      "Add",
      operandsOf(series).filter((term) => term.operator !== "BigO"),
    )
    .subs({ u: u0 + h, u0, m })
    .N().re;
  const f = (name: string) => ce.box([name, u0, m] as never).N().re;
  const [sn, cn, dn] = [f("JacobiSN"), f("JacobiCN"), f("JacobiDN")];
  expect(value).toBeCloseTo(sn + cn * dn * h - 0.5 * (m * cn * cn + dn * dn) * sn * h * h, 12);
});
